import { STORAGE_KEYS, state } from "./ui/state.js";
import { storageGet } from "./ui/dom.js";
import { setConnectionStatus, loadSnapshot, switchTab } from "./ui/engine-client.js";
import { renderAll } from "./ui/render-shared.js";
import { applyTheme, initializeDesktopWindowControls } from "./ui/desktop.js";
import { applyMinimalMode } from "./ui/minimal.js";
import { bindHeaderLayout } from "./ui/header-layout.js";
import { bindIconTooltips } from "./ui/icon-tooltips.js";
import { initTabOrder } from "./ui/tab-order.js";
import { bindEvents } from "./ui/events.js";
import { loadNoteLengthPreferences } from "./ui/note-length-preferences.js";
import { loadPinEffectPreferences } from "./ui/pin-effect-preferences.js";

if (window.perchDesktop?.getPathForFile) document.documentElement.dataset.desktop = "true";
loadNoteLengthPreferences();
loadPinEffectPreferences();
const savedSortMode = storageGet(STORAGE_KEYS.sortMode);
if (savedSortMode) state.sortMode = savedSortMode;
applyTheme(storageGet(STORAGE_KEYS.theme) || "dark");
applyMinimalMode(storageGet(STORAGE_KEYS.minimalMode) === "true", { persist: false, render: false });
setConnectionStatus("connecting", "正在连接 WorkPerch…", "业务数据由 Engine Server 单一持有。");
renderAll();
initTabOrder();
switchTab(location.hash.slice(1) || storageGet(STORAGE_KEYS.activeTab) || "paths", false);
if (storageGet(STORAGE_KEYS.minimalMode) === "true") switchTab("paths", false);
bindEvents();
bindHeaderLayout();
bindIconTooltips();
initializeDesktopWindowControls();
loadSnapshot();
